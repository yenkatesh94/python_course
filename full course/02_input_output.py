"""input() reads text entered by a user, and print() displays information.
This example asks for two values and uses them in a friendly response.
"""

# Topic 2: Input and output
# input() displays a prompt and reads text typed by the user.
name = input("What is your name? ")
favorite_subject = input("What is your favorite subject? ")

# print() displays output on the screen.
print(f"Hello, {name}!")
print(f"{favorite_subject} sounds interesting.")